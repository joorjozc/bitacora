/* Construye el bloque de frases del viaje: recorre el catálogo,
   traduce con el idioma que toque y descarta las categorías de
   perfil que este viajero no ha pedido. */
function construirFrases(codigoIdioma, perfiles) {
  var idi = IDIOMAS[codigoIdioma];
  if (!idi || codigoIdioma === 'es') return [];
  perfiles = perfiles || [];

  var salida = [];
  CATALOGO_FRASES.forEach(function (grupo) {
    if (grupo.perfil && perfiles.indexOf(grupo.perfil) === -1) return;
    var items = [];
    grupo.claves.forEach(function (par) {
      var t = idi.f[par[0]];
      if (t) items.push([par[1], t[0], t[1]]);
    });
    if (items.length) salida.push({ cat: grupo.cat, items: items });
  });
  return salida;
}
